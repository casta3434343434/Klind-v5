const orderedTranslations = Object.entries(translations).sort((a, b) => b[0].length - a[0].length);
const originals = new WeakMap();

function translate(value, language) {
  if (language !== 'en' || !value.trim()) return value;
  let result = value;
  orderedTranslations.forEach(([from, to]) => {
    const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const boundary = /^[A-Za-zÀ-ÿ].*[A-Za-zÀ-ÿ]$/.test(from) ? `(?<![A-Za-zÀ-ÿ])${escaped}(?![A-Za-zÀ-ÿ])` : escaped;
    result = result.replace(new RegExp(boundary, 'g'), to);
  });
  return result;
}

function updateTree(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest('script,style')) continue;
    if (!originals.has(node)) originals.set(node, node.nodeValue);
    const original = originals.get(node);
    const next = language === 'en' ? translate(original, language) : original;
    if (node.nodeValue !== next) node.nodeValue = next;
  }
  root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach(element => {
    ['placeholder', 'title', 'aria-label'].forEach(attribute => {
      const current = element.getAttribute(attribute);
      if (!current) return;
      const key = `${attribute}:${element}`;
      if (!element.dataset.i18nOriginal) element.dataset.i18nOriginal = JSON.stringify({ ...(element.dataset.i18nOriginal ? JSON.parse(element.dataset.i18nOriginal) : {}), [attribute]: current });
      const stored = JSON.parse(element.dataset.i18nOriginal)[attribute];
      element.setAttribute(attribute, language === 'en' ? translate(stored, language) : stored);
    });
  });
}

export function installTranslations(language) {
  updateTree(document.body, language);
  const observer = new MutationObserver(records => {
    records.forEach(record => record.addedNodes.forEach(node => {
      if (node.nodeType === Node.ELEMENT_NODE) updateTree(node, language);
      if (node.nodeType === Node.TEXT_NODE && !originals.has(node)) originals.set(node, node.nodeValue);
    }));
  });
  observer.observe(document.body, { childList: true, subtree: true });
  return observer;
}
